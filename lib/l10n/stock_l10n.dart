/// Translate a `stock.*` key for the current locale.
/// Falls back to English, then the key itself.
String stockTr(String key) {
  final lang = AppLocale.current.value;
  return stockStrings[lang]?[key] ??
      stockStrings['en']![key] ??
      key;
}
