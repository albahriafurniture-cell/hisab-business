/// Translate a bank/reports key for the current [AppLocale].
/// Falls back to English, then to the key itself.
String bankTr(String key) {
  final lang = AppLocale.current.value;
  return bankStrings[lang]?[key] ?? bankStrings['en']![key] ?? key;
}
